export function MedicalIcon({
  name,
  size = 20,
  className,
  strokeWidth = 1.8,
}: {
  name: string
  size?: number
  className?: string
  strokeWidth?: number
}) {
  const key = name.toString()
  const Icon = ICON_MAP[key] ?? ICON_MAP[key.toLowerCase()] ?? ICON_MAP.default
  return <Icon size={size} strokeWidth={strokeWidth} className={className} />
}
